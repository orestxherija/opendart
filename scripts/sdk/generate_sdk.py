def python_name(field: str, names: dict[str, str]) -> str:
    """Return a reviewed Python name, escaping reserved model field names.

    Args:
        field (str): OpenDART request or response field name.
        names (dict[str, str]): Reviewed mapping of upstream to Python names.

    Returns:
        str: Python attribute name for the field.
    """
    name = names.get(field, field)
    return name + "_" if keyword.iskeyword(name) or name.startswith("model_") else name


def check_names(fields: Sequence[str], names: dict[str, str]) -> None:
    """Reject a model whose distinct wire fields would share a Python name.

    Args:
        fields (Sequence[str]): Wire fields in one request or response model.
        names (dict[str, str]): Reviewed mapping of upstream to Python names.

    Raises:
        ValueError: Two wire fields map to the same Python attribute.
    """
    converted = [python_name(field, names) for field in fields]
    if len(converted) != len(set(converted)):
        raise ValueError(f"Duplicate Python field after renaming: {fields}")


def docstring(
    summary: str,
    *,
    indent: int = 0,
    args: Sequence[tuple[str, str, str]] = (),
    attributes: Sequence[tuple[str, str, str]] = (),
    returns: tuple[str, str] | None = None,
    raises: Sequence[tuple[str, str]] = (),
    note: str = "",
) -> str:
    """Render a Google-style docstring as indented Python source.

    Args:
        summary (str): One-line description of the documented object.
        indent (int): Number of leading spaces in the generated source.
        args (Sequence[tuple[str, str, str]]): Argument names, types, and descriptions.
        attributes (Sequence[tuple[str, str, str]]): Attribute names, types, and descriptions.
        returns (tuple[str, str] | None): Return type and description, if applicable.
        raises (Sequence[tuple[str, str]]): Exception names and the conditions that raise them.
        note (str): Additional prose following the summary.

    Returns:
        str: A triple-quoted docstring, including its trailing newline.
    """
    lines = [summary]
    width = max(60, 100 - indent)
    if note:
        lines.extend(["", *textwrap.wrap(" ".join(note.split()), width=width)])
    for title, entries in (("Args", args), ("Attributes", attributes)):
        if entries:
            lines.extend(["", f"{title}:"])
            for name, kind, description in entries:
                lines.extend(
                    textwrap.wrap(
                        f"{name} ({kind}): {" ".join(description.split())}",
                        width=width,
                        initial_indent="    ",
                        subsequent_indent="        ",
                        break_long_words=False,
                        break_on_hyphens=False,
                    )
                )
    if returns:
        lines.extend(["", "Returns:", f"    {returns[0]}: {returns[1]}"])
    if raises:
        lines.extend(["", "Raises:"])
        for kind, description in raises:
            lines.extend(
                textwrap.wrap(
                    f"{kind}: {description}",
                    width=width,
                    initial_indent="    ",
                    subsequent_indent="        ",
                )
            )
    content = "\n".join(lines).replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if len(lines) == 1:
        return " " * indent + '"""' + content + '"""\n'
    return textwrap.indent('"""' + content + '\n"""\n', " " * indent)


def documented_type(schema: dict, annotation: str) -> str:
    """Describe a field type without repeating Pydantic constraint metadata.

    Args:
        schema (dict): OpenAPI schema for the field.
        annotation (str): Generated annotation, including nested model names.

    Returns:
        str: A readable scalar, collection, model, or union type.
    """
    if schema.get("type") in {"string", "integer"}:
        return {"string": "str", "integer": "int"}[schema["type"]]
    return annotation.replace("builtins.", "")


def parameter_description(parameter: dict) -> str:
    """Include omission behavior and enum choices in a parameter description.

    Args:
        parameter (dict): Resolved OpenAPI query parameter.

    Returns:
        str: Upstream description with enum choices and optional defaults.
    """
    description = parameter["description"].strip().rstrip(".") + "."
    schema = parameter["schema"]
    if "enum" in schema:
        description += " Allowed values: " + ", ".join(repr(item) for item in schema["enum"]) + "."
    if not parameter.get("required", False):
        description += " None omits this parameter."
        if "default" in schema:
            description += f" The upstream default is {schema["default"]!r}."
    return description


def snake(value: str) -> str:
    """Convert a camel-case endpoint stem to a snake-case Python name.

    Args:
        value (str): Endpoint stem or category name; hyphens are also converted.

    Returns:
        str: Lowercase name with underscore separators.
    """
    return re.sub(r"(?<!^)(?=[A-Z])", "_", value).lower().replace("-", "_")


def pascal(value: str) -> str:
    """Capitalize and concatenate the parts of an underscore-separated name.

    Args:
        value (str): Underscore-separated identifier.

    Returns:
        str: Pascal-case class name.
    """
    return "".join(part[:1].upper() + part[1:] for part in value.split("_"))


def resolve(reference: str, source: Path) -> dict:
    """Load a local YAML reference relative to its containing document.

    Args:
        reference (str): Reference containing a filename and # pointer.
        source (Path): YAML document containing the reference.

    Returns:
        dict: Referenced schema or parameter mapping.

    Raises:
        ValueError: The reference has no # separator.
        KeyError: A pointer component is absent.
        OSError: The referenced file cannot be read.
        yaml.YAMLError: The referenced YAML is invalid.
    """
    filename, pointer = reference.split("#", 1)
    document = yaml.safe_load((source.parent / filename if filename else source).read_text())
    for part in pointer.lstrip("/").split("/"):
        document = document[part]
    return document


def scalar(schema: dict) -> str:
    """Translate a supported scalar or scalar-array schema into a Python annotation.

    Args:
        schema (dict): OpenAPI schema containing a supported type, enum, or constraint.

    Returns:
        str: Python annotation with Literal values or Pydantic constraints as needed.

    Raises:
        ValueError: The schema has an unsupported scalar type.
    """
    if "enum" in schema:
        return f"Literal[{", ".join(repr(value) for value in schema["enum"])}]"
    kind = schema.get("type")
    if kind == "array":
        base = f"builtins.list[{scalar(schema["items"])}]"
    elif kind in ("string", "integer"):
        base = {"string": "str", "integer": "int"}[kind]
    else:
        raise ValueError(f"Unsupported scalar: {schema}")
    constraints = {
        "minLength": "min_length",
        "maxLength": "max_length",
        "pattern": "pattern",
        "minimum": "ge",
        "maximum": "le",
        "minItems": "min_length",
        "maxItems": "max_length",
    }
    fields = [f"{target}={schema[key]!r}" for key, target in constraints.items() if key in schema]
    return f"Annotated[{base}, Field({", ".join(fields)})]" if fields else base


class ModelWriter:
    """Accumulate response model definitions in dependency order.

    Attributes:
        classes (list[str]): Generated class source, with nested models before their
            parents.
    """

    def __init__(self) -> None:
        """Initialize an empty collection of generated response classes."""
        self.classes: list[str] = []

    def annotation(self, schema: dict, name: str) -> str:
        """Resolve a schema annotation and emit any nested response model classes.

        Args:
            schema (dict): Field schema containing an object, array, union, or scalar.
            name (str): Class-name prefix for nested objects and union branches.

        Returns:
            str: Python annotation referring to any generated model classes.

        Raises:
            ValueError: A nested scalar schema is unsupported.
        """
        if "anyOf" in schema:
            return " | ".join(
                self.annotation(item, f"{name}Variant{index}")
                for index, item in enumerate(schema["anyOf"], 1)
            )
        if schema.get("type") == "object":
            self.add(schema, name)
            return name
        if schema.get("type") == "array":
            return f"builtins.list[{self.annotation(schema["items"], name + "Item")}]"
        return scalar(schema)

    def add(self, schema: dict, name: str) -> None:
        """Append a documented response class after emitting its nested models.

        Args:
            schema (dict): Object schema with field descriptions and required names.
            name (str): Python class name to emit.

        Raises:
            ValueError: A field uses an unsupported scalar schema.
        """
        fields = []
        attributes = []
        required = schema.get("required", [])
        check_names(list(schema.get("properties", {})), RESPONSE_NAMES)
        for field, definition in schema.get("properties", {}).items():
            python_field = python_name(field, RESPONSE_NAMES)
            annotation = self.annotation(definition, name + pascal(python_field))
            arguments = [f"description={definition.get("description", "")!r}"]
            if python_field != field:
                arguments.append(f"alias={field!r}")
            if field not in required:
                annotation += " | None"
                arguments.insert(0, "default=None")
            kind = documented_type(definition, annotation)
            if field not in required and not kind.endswith(" | None"):
                kind += " | None"
            description = definition.get("description", "Value reported by OpenDART.")
            description = description.strip().rstrip(".") + "."
            if "enum" in definition:
                description += (
                    " Allowed values: " + ", ".join(repr(item) for item in definition["enum"]) + "."
                )
            if field not in required:
                description += " Defaults to None when absent."
            if python_field != field:
                description += f" Serialized under the upstream name {field!r}."
            attributes.append((python_field, kind, description))
            fields.append(f"    {python_field}: {annotation} = Field({", ".join(arguments)})")
        description = schema.get("description", f"Validated response fields for {name}.")
        summary, _, detail = description.partition(". ")
        docs = docstring(
            summary.rstrip(".") + ".",
            indent=4,
            attributes=attributes,
            raises=[("pydantic.ValidationError", "Fields do not match the response schema.")],
            note=detail,
        )
        self.classes.append(
            f"class {name}(ResponseModel):\n" + docs + "\n" + "\n".join(fields or ["    pass"])
        )


def generate() -> dict[str, str]:
    """Generate documented SDK modules from the checked-in OpenAPI reference.

    Returns:
        dict[str, str]: Destination-relative Python filenames mapped to source code.

    Raises:
        ValueError: A scalar schema or reference format is unsupported.
        KeyError: The reference is missing a required schema or operation entry.
        OSError: A reference document cannot be read.
        yaml.YAMLError: A reference document contains invalid YAML.
    """
    files = {}
    exports = []
    model_names = []
    for path_file in sorted((REFERENCE / "paths").glob("*.yaml")):
        group = path_file.stem.replace("-", "_")
        class_name = pascal(group)
        requests = []
        writer = ModelWriter()
        schemas = yaml.safe_load((REFERENCE / "schemas" / path_file.name).read_text())
        for name, schema in schemas.items():
            if name.endswith("Success"):
                writer.add(schema, name.removesuffix("Success") + "Response")
        model_imports = []
        request_imports = []
        methods = []
        paths = yaml.safe_load(path_file.read_text())
        for path, item in paths.items():
            operation = item["get"]
            content = operation["responses"]["200"]["content"]
            archive = "application/zip" in content
            if not archive and not path.endswith(".json"):
                continue
            stem = path.split(".")[0].lstrip("/")
            name = stem[0].upper() + stem[1:]
            request_name = name + "Request"
            response_name = "bytes" if archive else name + "Response"
            method_name = {"list": "search", "corpCode": "corporation_codes"}.get(stem, snake(stem))
            parameters = [resolve(p["$ref"], path_file) for p in operation.get("parameters", [])]
            parameter_names = PARAMETER_NAMES.copy()
            if any(
                parameter["name"] == "corp_code" and parameter["schema"]["type"] == "array"
                for parameter in parameters
            ):
                parameter_names["corp_code"] = "corporation_codes"
            check_names([parameter["name"] for parameter in parameters], parameter_names)
            request_fields = []
            documented_args = []
            arguments = []
            values = []
            for parameter in parameters:
                field = parameter["name"]
                python_field = python_name(field, parameter_names)
                schema = parameter["schema"]
                annotation = scalar(schema)
                public_type = {"string": "str", "integer": "int", "array": "list[str]"}[
                    schema["type"]
                ]
                if "enum" in schema:
                    public_type = scalar(schema)
                required = parameter.get("required", False)
                default = "" if required else " | None = None"
                if not required:
                    annotation += " | None"
                request_fields.append(
                    f"    {python_field}: {annotation} = Field("
                    + ("" if required else "default=None, ")
                    + f"description={parameter["description"]!r}, alias={field!r})"
                )
                arguments.append(f"        {python_field}: {public_type}{default},")
                values.append(f"{python_field}={python_field}")
                kind = documented_type(schema, public_type) + ("" if required else " | None")
                documented_args.append((python_field, kind, parameter_description(parameter)))
            request_docs = docstring(
                f"Query parameters for {operation["summary"].removesuffix(" (JSON)").removesuffix(" (ZIP)")}.",
                indent=4,
                args=documented_args,
                raises=[
                    ("pydantic.ValidationError", "A field violates its type or query constraints.")
                ]
                if documented_args
                else [],
            )
            requests.append(
                f"class {request_name}(RequestModel):\n"
                + request_docs
                + "\n"
                + "\n".join(request_fields or ["    pass"])
            )
            request_imports.append(request_name)
            if not archive:
                model_imports.append(response_name)
            signature = f"    async def {method_name}(\n        self,"
            if arguments:
                signature += "\n        *,\n" + "\n".join(arguments)
            signature += f"\n    ) -> {response_name}:\n"
            failures = []
            if documented_args:
                failures.append(
                    (
                        "pydantic.ValidationError",
                        "An argument violates its type or query constraints.",
                    )
                )
            failures.extend(
                [
                    (
                        "APIError",
                        "OpenDART reports a non-success application status. Subclasses identify no data, unavailable files, quota exhaustion, maintenance, or API rejection.",
                    ),
                    (
                        "UnavailableError",
                        "The request fails or HTTP status is 429 or at least 500.",
                    ),
                    ("RejectedError", "OpenDART returns an HTTP 4xx status other than 429."),
                    (
                        "ResponseTooLargeError",
                        "The body exceeds the configured "
                        + ("max_download_bytes" if archive else "max_response_bytes")
                        + " limit.",
                    ),
                    (
                        "ContractError",
                        "The HTTP status, content encoding, or response body is unexpected.",
                    ),
                    ("RuntimeError", "The parent SDK client has already been closed."),
                ]
            )
            body = docstring(
                operation["summary"].rstrip(".") + ".",
                indent=8,
                args=documented_args,
                returns=(
                    response_name,
                    "Complete ZIP archive bytes."
                    if archive
                    else "Validated successful response with the upstream field values.",
                ),
                raises=failures,
                note="Official guide: " + operation["externalDocs"]["url"],
            )
            body += f"        request = {request_name}({", ".join(values)})\n"
            if archive:
                body += f"        return await self._client.download({path!r}, request)\n"
            else:
                body += f"        return await self._client.request({path!r}, request, {response_name})\n"
            methods.append(signature + body)
        imports = (
            "from __future__ import annotations\n\nfrom typing import TYPE_CHECKING, Literal\n\n"
            + f"from opendart.models.{group} import {", ".join(request_imports + model_imports)}\n\n"
            + "if TYPE_CHECKING:\n    from opendart._transport import Transport\n\n"
        )
        resource = (
            f"class {class_name}:\n"
            + docstring(
                f"Asynchronous operations for {group.replace("_", " ")}.",
                indent=4,
                note="The parent SDK client owns and closes the shared HTTP transport.",
            )
            + "\n"
            + "    def __init__(self, client: Transport) -> None:\n"
            + docstring(
                "Bind resource operations to the parent client's transport.",
                indent=8,
                args=[("client", "Transport", "Shared transport owned by the parent SDK client.")],
            )
            + "        self._client = client\n\n"
            + "\n".join(methods)
        )
        files[f"resources/{group}.py"] = (
            HEADER
            + docstring(f"Typed asynchronous {group.replace("_", " ")} operations.")
            + "\n"
            + imports
            + resource
        )
        files[f"models/{group}.py"] = (
            HEADER
            + docstring(
                f"Validated request, response, and record models for {group.replace("_", " ")}."
            )
            + "\n"
            + "from __future__ import annotations\n\nimport builtins\nfrom typing import Annotated, Literal\n\n"
            + "from pydantic import Field\n\nfrom opendart.models._base import RequestModel, ResponseModel\n\n\n"
            + "\n\n\n".join(requests + writer.classes)
            + "\n"
        )
        exports.append(
            f"from opendart.models.{group} import {", ".join(request_imports + model_imports)}"
        )
        model_names.extend(request_imports + model_imports)
    files["models/__init__.py"] = (
        '"""Endpoint request and response models; nested records live in category modules."""\n'
        + HEADER
        + "\n".join(exports)
        + "\n"
    )
    files["resources/__init__.py"] = (
        '"""Typed resources grouped by the official API categories."""\n'
    )
    # Explicit exports keep generated re-exports visible to type checkers.
    files["models/__init__.py"] += f"\n__all__ = {model_names!r}\n"
    return files


def main() -> None:
    """Generate SDK files or check their freshness when --check is passed.

    Raises:
        SystemExit: CLI parsing exits, or --check finds stale generated files.
        subprocess.CalledProcessError: Ruff linting or formatting of generated code fails.
        ValueError: The reference uses an unsupported schema or reference format.
        KeyError: A required reference entry is missing.
        OSError: A reference or output file cannot be read or written.
        yaml.YAMLError: A reference document contains invalid YAML.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    stale = []
    with tempfile.TemporaryDirectory() as temporary:
        temp = Path(temporary)
        for filename, content in generated.items():
            target = temp / filename
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
        config = str(ROOT / "ruff.toml")
        subprocess.run(
            [
                sys.executable,
                "-m",
                "ruff",
                "check",
                "--config",
                config,
                # The generated files live in a temporary directory here, so the
                # repository's per-file ignores do not match their final paths.
                "--extend-ignore",
                "PLR0913,RUF001,RUF002,TC003,W505",
                "--fix",
                "--quiet",
                str(temp),
            ],
            check=True,
        )
        subprocess.run(
            [sys.executable, "-m", "ruff", "format", "--config", config, "--quiet", str(temp)],
            check=True,
        )
        for filename in generated:
            content = (temp / filename).read_text()
            target = DESTINATION / filename
            if args.check:
                if not target.exists() or target.read_text() != content:
                    stale.append(filename)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content)
    if stale:
        raise SystemExit("Stale generated SDK files: " + ", ".join(stale))
    print(f"{"Checked" if args.check else "Generated"} {len(generated)} SDK files")


if __name__ == "__main__":
    main()
