"""Generate opendart_analysis.catalog from the API catalog and the SDK naming rules, offline.

Labels and descriptions are the catalog's English text. Python names and SDK model names come
from scripts/generate_sdk.py, so they match the generated SDK exactly. Run with --check in CI.
"""

