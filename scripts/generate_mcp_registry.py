import importlib.util
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "api_reference/sources/catalog.json"
PATHS = ROOT / "api_reference/paths"
DESTINATION = ROOT / "packages/analysis/src/opendart_analysis/catalog"
FILENAME = "_generated.py"
HEADER = "# Generated by scripts/generate_mcp_registry.py; do not edit.\n"
# Response envelope and pagination counters; they describe the response, not a record.
ENVELOPE = frozenset({"status", "message", "page_no", "page_count", "total_count", "total_page"})
# Titles that mean nothing out of the guide's table layout; the description is used instead.
UNINFORMATIVE = frozenset({"", "-", "etc", "etc.", "other", "others"})

# Reviewed corrections for catalog titles that are truncated or name the wrong column. The
# catalog description is still kept verbatim in FieldSpec.description.
LABEL_OVERRIDES = {
    # Title and description both say "Corporation code" for the corp_name column.
    ("AE00018", "corp_name"): "Corporation name",
    # Truncated to 'Interest rate("'; the bond-with-warrants guide names the same column.
    ("AE00057", "bd_intr_sf"): "Interest rate(Yield to maturity (%))",
    ("AE00058", "nstk_isstk_tisstk_vs"): (
        "Details of warrants(Shares to be issued by exercise of warrants"
        "(Ratio to total number of shares (%)))"
    ),
    # The end-date column is titled as a start date, and the start-date column as an end date.
    ("AE00064", "ctr_pd_edd"): "Contract period(End date)",
    ("AE00077", "extrsc_osprpd_bgd"): (
        "Swap/transfer schedule(Period for submission of old share certificates(Start date))"
    ),
    # Truncated; the business-acquisition guide titles the same column in full.
    ("AE00067", "gmtsck_prd"): "Scheduled date of general shareholders' meeting",
}

# Kinds the title rules cannot infer: rows whose unit varies, unit-less quantities, and titles
# that name a qualifier rather than the value. Keys are wire names, or (api_id, wire name).
KIND_OVERRIDES: dict[str | tuple[str, str], str] = {
    # Dividend columns hold KRW millions, KRW per share, and percentages by row; indicator
    # values are percentages or multiples by indicator.
    "thstrm": "number",
    "frmtrm": "number",
    "lwfr": "number",
    "idx_val": "number",
    # Term dates are "as of" dates or ranges depending on the statement.
    "thstrm_dt": "period",
    "frmtrm_dt": "period",
    "bfefrmtrm_dt": "period",
    # Quantities whose titles carry no unit.
    "apnt": "count",
    "rlsofc": "count",
    "mdstrm_resig": "count",
    "bsis_qy": "count",
    "avrg_cnwk_sdytrn": "count",
    "tot_reqre_time": "count",
    "stkqy_irds": "count",
    "d1_prodlm_ostk": "count",
    "d1_prodlm_estk": "count",
    "d1_slodlm_ostk": "count",
    "d1_slodlm_estk": "count",
    ("AE00012", "sm"): "count",
    # "(from total remuneration)" qualifies these columns; it is not their unit.
    "stk_bsd_pd_mendng_totamt_knd": "text",
    "stk_bsd_pd_mendng_totamt_qty": "count",
    # "Current standard": the date the financial position is stated at.
    "ffdtl_std": "date",
    "atdvfdtl_std": "date",
    "estk_exrt": "percent",
    "dpcr_amt": "amount",
    "stk_cd": "text",
    # Letter codes for the market division, amendments, and withdrawals.
    ("AE00001", "rm"): "code",
}

CODE_FIELDS = frozenset({
    "rcept_no", "rpt_rcpn", "corp_code", "corp_cls", "stock_code", "reprt_code", "fs_div",
    "sj_div", "account_id", "idx_cl_code", "idx_code", "induty_code", "jurir_no", "bizr_no",
    "currency", "ord",
})  # fmt: skip
NUMERIC = re.compile(r"^(9,999,999,999(?![.\d])|0\.00$)")
MULTIPLIER = re.compile(r"^9,999,999,999\.9x")
DATE_FORMAT = re.compile(r"\(YYYYMMDD\)|^YYYY\.MM\.DD$|^YYYYMM$")
# Unit markers such as (KRW), (shrs.), and (A/B), and the formulas written with Roman numerals.
UNIT = re.compile(
    r"\s*(%|krw|krw/share|shrs\.?|no\.|[a-c]|[a-c]/[a-c]|\u2161-\u2162|\u2163-\u2164)\s*",
    re.IGNORECASE,
)
NUMERIC_KINDS = frozenset({"amount", "per_share", "count", "percent", "ratio"})
# Ordered rules for one title segment; the first match wins. The third item limits a rule to
# columns the catalog marks with a numeric placeholder (True) or without one (False). Numeric
# columns only take numeric kinds.
RULES = tuple(
    (re.compile(pattern, re.IGNORECASE), kind, numeric)
    for pattern, kind, numeric in (
        (r"\b(calculation|basis|methods?|procedures?|purpose|reasons?)\b", "text", False),
        (
            r"/share|\bper share\b|\bpar value\b|\bprice of shares\b|\b(exercise|conversion"
            r"|exchange|offering|underwriting|issuing|refixing|purchase|rights) price",
            "per_share",
            None,
        ),
        (r"\(\s*%\s*\)", "percent", None),
        (r"\(\s*shrs\.?\s*\)|\(\s*no\.\s*\)", "count", None),
        (r"\(\s*krw\s*\)", "amount", None),
        (r"(?<!\bto )\bdates?\b", "date", None),
        (r"^\s*(whether|subject to|applicable\b)|\bclassified as\b", "flag", None),
        (r"\b(names?|titles?|types?|class|details?|terms|opinion|matters)\b", "text", None),
        (r"\bperiod\b|\bfiscal years?\b|\bmonth of settlement\b", "period", None),
        (
            r"\b(interest|coupon) rate\b|\byield\b|\b(shareholding|holding|ownership) ratio\b"
            r"|\bratio of (ownership|increase)",
            "percent",
            None,
        ),
        (r"\bratios?\b", "ratio", None),
        (r"\bnumber of\b|\bquantity\b|\bheadcount\b|\bhours\b", "count", None),
        (r"\bamounts?\b|\bremuneration\b|\bsalary\b|\bcompensation\b|\bvalue\b", "amount", None),
        (r"\bcode\b|\bno\.|\bcurrency\b|\bordinal\b|\bid\b", "code", None),
        (r"\bshares\b|\bpresent\b|\babsent\b", "count", True),
    )
)


def load_sdk_generator() -> Any:
    """Import scripts/generate_sdk.py, the source of the SDK's naming rules."""
    spec = importlib.util.spec_from_file_location("generate_sdk", ROOT / "scripts/generate_sdk.py")
    if spec is None or spec.loader is None:
        raise ImportError("Cannot load scripts/generate_sdk.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


SDK = load_sdk_generator()


def clean(text: str) -> str:
    """Strip whitespace and the stray pair of wrapping quotes that some catalog titles carry."""
    text = text.strip()
    return text[1:-1].strip() if len(text) > 1 and text[0] == text[-1] == '"' else text


def label(api_id: str, field: dict[str, Any]) -> tuple[str, str]:
    """Return a field's label and its source: override, title, description, or name."""
    if (api_id, field["name"]) in LABEL_OVERRIDES:
        return LABEL_OVERRIDES[api_id, field["name"]], "override"
    title, description = clean(field["title"]), clean(field["description"])
    if title.casefold() not in UNINFORMATIVE and title != field["name"]:
        return title, "title"
    if description and not NUMERIC.match(description):
        return description, "description"
    return (title, "title") if title else (field["name"], "name")


def segments(text: str) -> list[str]:
    """Split a nested parenthetical title into segments, most specific first.

    Catalog titles qualify a column with nested parentheses, such as
    "Counterparty(Financial status (KRW)(Total assets))". Each level's own text is one segment,
    with unit markers like "(KRW)" kept in place; the chain follows the last group at each level.
    Unbalanced parentheses, which the catalog has, are tolerated.
    """

    def parse(index: int) -> tuple[tuple[str, list[Any]], int]:
        own: list[str] = []
        children: list[Any] = []
        while index < len(text):
            char = text[index]
            index += 1
            if char == ")":
                break
            if char != "(":
                own.append(char)
                continue
            child, index = parse(index)
            if UNIT.fullmatch(child[0]) and not child[1]:
                own.append(f"({child[0]})")
            else:
                own.append(" ")
                children.append(child)
        return (" ".join("".join(own).split()), children), index

    chain = []
    node, index = parse(0)
    while index < len(text):  # Text after a stray closing parenthesis.
        rest, index = parse(index)
        node = (f"{node[0]} {rest[0]}", node[1] + rest[1])
    while True:
        chain.append(node[0])
        if not node[1]:
            return [part for part in reversed(chain) if part.strip("\"' ")]
        node = node[1][-1]


def segment_kind(segment: str, *, numeric: bool) -> str | None:
    """Return the kind of the first rule that applies to and matches a segment, if any."""
    for pattern, kind, applies in RULES:
        allowed = applies in (None, numeric) and (kind in NUMERIC_KINDS or not numeric)
        if allowed and pattern.search(segment):
            return kind
    return None


def infer_kind(api_id: str, wire: str, title: str, description: str) -> str:
    """Infer a field's FieldKind from overrides, its upstream name, label, and description.

    Title segments decide first, most specific first; the description is the fallback, and a
    numeric placeholder such as 9,999,999,999 restricts the result to numeric kinds.
    """
    for key in ((api_id, wire), wire):
        if key in KIND_OVERRIDES:
            return KIND_OVERRIDES[key]
    if wire in CODE_FIELDS:
        return "code"
    # OpenDART suffixes yes/no columns with _at or _atn ("whether").
    if wire.endswith(("_at", "_atn")):
        return "flag"
    if MULTIPLIER.match(description):
        return "ratio"
    numeric = bool(NUMERIC.match(description))
    texts = [title]
    if description != title and not numeric:
        texts.append(description)
    for text in texts:
        for segment in segments(text):
            if kind := segment_kind(segment, numeric=numeric):
                return kind
    if DATE_FORMAT.search(description):
        return "date"
    if numeric:
        return "percent" if description == "0.00" else "amount"
    return "text"


def tree(service: dict[str, Any]) -> list[Any]:
    """Nest fields below the result root: field dicts, or (container, children) pairs."""
    fields = copy.deepcopy(service["fields"])
    if service["id"] in ("AE00038", "AE00039"):
        # As in scripts/api_reference/build.py: list children are rendered at the root indent.
        start = next(i for i, field in enumerate(fields) if field["name"] == "list")
        for field in fields[start + 1 :]:
            field["indent"] = 40
    root: list[Any] = []
    stack: list[tuple[int, list[Any]]] = [(fields[0]["indent"], root)]
    for field in fields[1:]:
        while stack[-1][0] >= field["indent"]:
            stack.pop()
        if field["container"]:
            children: list[Any] = []
            stack[-1][1].append((field, children))
            stack.append((field["indent"], children))
        else:
            stack[-1][1].append(field)
    return root


def field_spec(api_id: str, field: dict[str, Any]) -> dict[str, Any]:
    """Return FieldSpec arguments: SDK attribute name, wire name, label, and kind."""
    text, source = label(api_id, field)
    description = clean(field["description"])
    spec = {
        "name": SDK.python_name(field["name"], SDK.RESPONSE_NAMES),
        "wire": field["name"],
        "label": text,
        "description": description,
        "kind": infer_kind(api_id, field["name"], text, description),
    }
    if source != "title":
        spec["label_source"] = source
    return spec


def records(
    api_id: str, nodes: list[Any], model: str | None, path: tuple[str, ...] = ()
) -> list[dict[str, Any]]:
    """Return RecordSpec arguments for the containers below nodes, in catalog order.

    model names the SDK class of the enclosing object (None inside archives); nested class
    names follow generate_sdk.ModelWriter, and path holds the attributes leading to nodes.
    """
    found: list[dict[str, Any]] = []
    containers = [node for node in nodes if isinstance(node, tuple)]
    names = [container["name"] for container, _ in containers]
    for position, (container, children) in enumerate(containers):
        name = SDK.python_name(container["name"], SDK.RESPONSE_NAMES)
        # Repeated containers become anyOf variants in the SDK, numbered from 1.
        repeats = names[: position + 1].count(container["name"])
        variant = f"Variant{repeats}" if names.count(container["name"]) > 1 else ""
        child_model = model and f"{model}{SDK.pascal(name)}Item{variant}"
        scalars = [node for node in children if not isinstance(node, tuple)]
        section = ""
        if [node["name"] for node in scalars] == ["title"]:
            # A registration-statement section: a title followed by its own record list.
            section, scalars = clean(scalars[0]["description"]), []
        if scalars:
            fields = tuple(field_spec(api_id, node) for node in scalars)
            found.append({"path": (*path, name), "model": child_model, "fields": fields})
        for record in records(api_id, children, child_model, (*path, name)):
            if section:
                fields = record.pop("fields")
                record |= {"section": section, "fields": fields}
            found.append(record)
    return found


def operations() -> dict[str, dict[str, Any]]:
    """Map API IDs to SDK method, path, and parameter names, read as generate_sdk.py does."""
    found = {}
    for path_file in sorted(PATHS.glob("*.yaml")):
        resource = path_file.stem.replace("-", "_")
        for path, item in yaml.safe_load(path_file.read_text(encoding="utf-8")).items():
            operation = item["get"]
            archive = "application/zip" in operation["responses"]["200"]["content"]
            if not archive and not path.endswith(".json"):
                continue
            stem = path.split(".")[0].lstrip("/")
            names = SDK.PARAMETER_NAMES.copy()
            parameters = [
                SDK.resolve(p["$ref"], path_file) for p in operation.get("parameters", [])
            ]
            if any(p["name"] == "corp_code" and p["schema"]["type"] == "array" for p in parameters):
                names["corp_code"] = "corporation_codes"
            found[operation["x-upstream-api-id"]] = {
                "resource": resource,
                "name": {"list": "search", "corpCode": "corporation_codes"}.get(
                    stem, SDK.snake(stem)
                ),
                "path": path,
                "archive": archive,
                "model": None if archive else stem[0].upper() + stem[1:] + "Response",
                "params": {p["name"]: SDK.python_name(p["name"], names) for p in parameters},
            }
    return found


def service_spec(group: str, service: dict[str, Any], operation: dict[str, Any]) -> dict[str, Any]:
    """Return ServiceSpec arguments, omitting empty defaults, for one catalog service."""
    params = [p for p in service["parameters"] if p["name"] != "crtfc_key"]
    if [p["name"] for p in params] != list(operation["params"]):
        raise ValueError(f"Parameters differ from the OpenAPI reference: {service["id"]}")
    nodes = tree(service)
    # The corporation directory documents the XML members of its ZIP archive.
    model = None if operation["archive"] else operation["model"]
    spec = {
        "name": operation["name"],
        "resource": operation["resource"],
        "api_id": service["id"],
        "group": group,
        "title": clean(service["title"]),
        "description": clean(service["description"]),
        "path": operation["path"],
        "guide_url": service["source"],
        "params": tuple(
            {
                "name": operation["params"][p["name"]],
                "wire": p["name"],
                "title": clean(p["title"]),
                "required": p["required"],
                "description": clean(p["description"]),
            }
            for p in params
        ),
        "records": tuple(records(service["id"], nodes, model)),
        "scalar_fields": tuple(
            field_spec(service["id"], node)
            for node in nodes
            if not isinstance(node, tuple) and node["name"] not in ENVELOPE
        ),
        "archive": operation["archive"],
    }
    return {key: value for key, value in spec.items() if value not in ((), False)}


def build() -> list[dict[str, Any]]:
    """Return ServiceSpec arguments for every catalog service, in catalog order."""
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    found = operations()
    specs = [
        service_spec(group["code"], service, found.pop(service["id"]))
        for group in catalog["groups"]
        for service in group["services"]
    ]
    names = [spec["name"] for spec in specs]
    if found or len(names) != len(set(names)):
        raise ValueError(f"Unmatched operations {sorted(found)} or repeated method names")
    return specs


FIELD_ORDER = ("name", "wire", "label", "description", "kind", "label_source")
"""FieldSpec parameters in declaration order, which a test checks. FieldSpec makes up most of
the module, so it is written positionally to stay under the repository's file-size limit."""

NESTED = {"params": "ParamSpec", "records": "RecordSpec"}
NESTED |= {"fields": "FieldSpec", "scalar_fields": "FieldSpec"}


def text(value: str) -> str:
    """Quote a string as the formatter would: double quotes unless that adds escapes."""
    quoted = repr(value)
    if quoted.startswith("'") and '"' not in value and "'" not in value:
        quoted = f'"{quoted[1:-1]}"'
    return quoted


def literal(value: Any, kind: str = "", depth: int = 0) -> str:
    """Render built data as a Python expression; kind names the constructor of a dict.

    ServiceSpec and RecordSpec take one keyword argument per line, ParamSpec fits on one
    line, and FieldSpec is positional on one line; depth sets the indentation.
    """
    pad = "    " * depth
    if isinstance(value, dict):
        if kind == "FieldSpec":
            present = [key for key in FIELD_ORDER if key in value]
            if len(present) != len(value) or present != list(FIELD_ORDER[: len(present)]):
                raise ValueError(f"FieldSpec arguments {sorted(value)} do not follow FIELD_ORDER")
            return f"FieldSpec({", ".join(literal(value[key]) for key in present)})"
        arguments = [f"{k}={literal(v, NESTED.get(k, ""), depth + 1)}" for k, v in value.items()]
        if kind == "ParamSpec":
            return f"ParamSpec({", ".join(arguments)})"
        return f"{kind}(\n" + "".join(f"{pad}    {item},\n" for item in arguments) + f"{pad})"
    if isinstance(value, tuple):
        if value and all(isinstance(item, dict) for item in value):
            items = "".join(f"{pad}    {literal(item, kind, depth + 1)},\n" for item in value)
            return f"(\n{items}{pad})"
        parts = [literal(item, kind) for item in value]
        return "(" + ", ".join(parts) + ("," if len(parts) == 1 else "") + ")"
    return text(value) if isinstance(value, str) else repr(value)


def render(specs: list[dict[str, Any]]) -> str:
    """Render the catalog module for the output of build(), laid out by literal()."""
    entries = "".join(
        f"    {text(spec["name"])}: {literal(spec, "ServiceSpec", 1)},\n" for spec in specs
    )
    return (
        HEADER
        + '"""Specs for every OpenDART service: SDK names, catalog labels, and value kinds."""\n\n'
        + "from __future__ import annotations\n\n"
        + "from types import MappingProxyType\nfrom typing import TYPE_CHECKING, Final\n\n"
        + "from opendart_analysis.catalog.specs import FieldSpec, ParamSpec, RecordSpec, ServiceSpec\n\n"
        + "if TYPE_CHECKING:\n    from collections.abc import Mapping\n\n"
        + "# fmt: off\n"
        + "SERVICES: Final[Mapping[str, ServiceSpec]] = MappingProxyType({\n"
        + entries
        + "})\n"
        + "# fmt: on\n"
        + "SERVICE_NAMES: Final[tuple[str, ...]] = tuple(SERVICES)\n"
    )


def main() -> None:
    """Write the catalog module, or with --check exit non-zero listing stale files."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = {FILENAME: render(build())}
    stale = []
    with tempfile.TemporaryDirectory() as temporary:
        temp = Path(temporary)
        for filename, content in generated.items():
            (temp / filename).write_text(content, encoding="utf-8")
        config = ["--config", str(ROOT / "ruff.toml"), "--quiet", str(temp)]
        # The temporary path is outside any package and misses the repository's per-file
        # ignores; the catalog text keeps typographic quotes and similar characters.
        for command in (["check", "--extend-ignore", "INP001,RUF001", "--fix"], ["format"]):
            subprocess.run([sys.executable, "-m", "ruff", *command, *config], check=True)  # noqa: S603
        for filename in generated:
            content = (temp / filename).read_text(encoding="utf-8")
            target = DESTINATION / filename
            if args.check:
                if not target.exists() or target.read_text(encoding="utf-8") != content:
                    stale.append(filename)
            else:
                target.write_text(content, encoding="utf-8")
    if stale:
        raise SystemExit("Stale generated service catalog files: " + ", ".join(stale))
    print(f"{"Checked" if args.check else "Generated"} {len(generated)} service catalog file")


if __name__ == "__main__":
    main()
